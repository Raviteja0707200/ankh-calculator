/**
 * 02-percent-power-root-factorial.test.js
 * Percentage semantics (Casio-style context sensitivity), powers, roots,
 * and factorials.
 */

'use strict';

const { test, testError, section, printSummary } = require('./test-harness.js');

// ---------------------------------------------------------------------------
section('percentage: standalone (divide by 100)');
// ---------------------------------------------------------------------------
test('25%', '0.25');
test('1%', '0.01');
test('100%', '1');
test('0%', '0');
test('50%', '0.5');
test('200%', '2');
test('0.5%', '0.005');
test('33.33%', '0.3333');

// ---------------------------------------------------------------------------
section('percentage: + / - context (percent of the other operand)');
// ---------------------------------------------------------------------------
test('500+10%', '550');
test('500-10%', '450');
test('1000+50%', '1500');
test('1000-50%', '500');
test('200+100%', '400');
test('200-100%', '0');
test('80+25%', '100');
test('80-25%', '60');
test('1000+0%', '1000');
test('1000-0%', '1000');
test('100+200%', '300');
test('50+10%', '55');
test('250+20%', '300');

// ---------------------------------------------------------------------------
section('percentage: * / context (percent as plain fraction)');
// ---------------------------------------------------------------------------
test('500*10%', '50');
test('500/10%', '5000');
test('200*50%', '100');
test('200/50%', '400');
test('1000*1%', '10');
test('1000/1%', '100000');
test('80*25%', '20');
test('400/20%', '2000');

// ---------------------------------------------------------------------------
section('percentage: combined with other operators');
// ---------------------------------------------------------------------------
test('(500+10%)*2', '1100');
test('500+10%+10', '560');
test('100+10%-5', '105');

// ---------------------------------------------------------------------------
section('powers: integer exponents');
// ---------------------------------------------------------------------------
test('2^0', '1');
test('2^1', '2');
test('2^2', '4');
test('2^3', '8');
test('2^4', '16');
test('2^5', '32');
test('2^6', '64');
test('2^7', '128');
test('2^8', '256');
test('2^9', '512');
test('2^10', '1024');
test('3^3', '27');
test('5^3', '125');
test('10^2', '100');
test('10^3', '1000');
test('10^6', '1000000');
test('7^2', '49');
test('9^2', '81');
test('12^2', '144');
test('1^100', '1');
test('100^0', '1');

// ---------------------------------------------------------------------------
section('powers: negative exponents');
// ---------------------------------------------------------------------------
test('2^-1', '0.5');
test('2^-2', '0.25');
test('2^-3', '0.125');
test('2^-4', '0.0625');
test('2^-5', '0.03125');
test('4^-1', '0.25');
test('5^-1', '0.2');
test('10^-1', '0.1');
test('10^-2', '0.01');
test('10^-4', '0.0001');

// ---------------------------------------------------------------------------
section('powers: negative bases');
// ---------------------------------------------------------------------------
test('(-2)^2', '4');
test('(-2)^3', '-8');
test('(-3)^2', '9');
test('(-3)^3', '-27');
test('(-1)^100', '1');
test('(-1)^101', '-1');
test('(-5)^0', '1');

// ---------------------------------------------------------------------------
section('square roots');
// ---------------------------------------------------------------------------
test('√0', '0');
test('√1', '1');
test('√4', '2');
test('√9', '3');
test('√16', '4');
test('√25', '5');
test('√36', '6');
test('√49', '7');
test('√64', '8');
test('√81', '9');
test('√100', '10');
test('√121', '11');
test('√144', '12');
test('√169', '13');
test('√196', '14');
test('√225', '15');
test('√625', '25');
test('√10000', '100');
test('√1000000', '1000');
testError('√(-4)', 'NEGATIVE_SQRT');
testError('√(-1)', 'NEGATIVE_SQRT');

// ---------------------------------------------------------------------------
section('cube roots');
// ---------------------------------------------------------------------------
test('∛0', '0');
test('∛1', '1');
test('∛8', '2');
test('∛27', '3');
test('∛64', '4');
test('∛125', '5');
test('∛216', '6');
test('∛343', '7');
test('∛512', '8');
test('∛729', '9');
test('∛1000', '10');
test('∛-8', '-2');
test('∛-27', '-3');
test('∛-1', '-1');

// ---------------------------------------------------------------------------
section('roots combined with other operators');
// ---------------------------------------------------------------------------
test('√25+5', '10');
test('√36+√64', '14');
test('√36*2', '12');
test('2*√36', '12');
test('√(36+64)', '10');
test('∛8+∛27', '5');

// ---------------------------------------------------------------------------
section('factorials');
// ---------------------------------------------------------------------------
test('0!', '1');
test('1!', '1');
test('2!', '2');
test('3!', '6');
test('4!', '24');
test('5!', '120');
test('6!', '720');
test('7!', '5040');
test('8!', '40320');
test('9!', '362880');
test('10!', '3628800');
test('11!', '39916800');
test('12!', '479001600');
test('13!', '6227020800');
test('14!', '87178291200');
test('15!', '1307674368000');
test('20!', '2432902008176640000');
testError('(-1)!', 'INVALID_FACTORIAL');
testError('(-5)!', 'INVALID_FACTORIAL');
testError('5.5!', 'INVALID_FACTORIAL');
testError('0.5!', 'INVALID_FACTORIAL');

// ---------------------------------------------------------------------------
section('factorials combined with other operators');
// ---------------------------------------------------------------------------
test('3!+4!', '30');
test('5!-4!', '96');
test('3!*2', '12');
test('2*3!', '12');
test('(3+2)!', '120');
test('5!/5', '24');

if (require.main === module) {
  const { failCount } = printSummary('PERCENT / POWER / ROOT / FACTORIAL');
  process.exitCode = failCount > 0 ? 1 : 0;
}
