/**
 * 04-indian-formatting.test.js
 * Indian comma-grouping (lakh/crore) number formatting.
 */

'use strict';

const { testFormat, section, printSummary } = require('./test-harness.js');

// ---------------------------------------------------------------------------
section('formatting: spec examples');
// ---------------------------------------------------------------------------
testFormat('1', '1');
testFormat('12', '12');
testFormat('123', '123');
testFormat('1234', '1,234');
testFormat('12345', '12,345');
testFormat('123456', '1,23,456');
testFormat('1234567', '12,34,567');
testFormat('12345678', '1,23,45,678');
testFormat('123456789', '12,34,56,789');
testFormat('1234567890', '1,23,45,67,890');

// ---------------------------------------------------------------------------
section('formatting: zero / single / double digit');
// ---------------------------------------------------------------------------
testFormat('0', '0');
for (let i = 0; i <= 999; i++) {
  testFormat(String(i), String(i)); // no commas under 1000
}

// ---------------------------------------------------------------------------
section('formatting: thousand range (1,000 - 99,999)');
// ---------------------------------------------------------------------------
testFormat('1000', '1,000');
testFormat('9999', '9,999');
testFormat('10000', '10,000');
testFormat('99999', '99,999');
testFormat('50000', '50,000');
testFormat('25000', '25,000');

// ---------------------------------------------------------------------------
section('formatting: lakh range');
// ---------------------------------------------------------------------------
testFormat('100000', '1,00,000');
testFormat('999999', '9,99,999');
testFormat('500000', '5,00,000');
testFormat('1000000', '10,00,000');
testFormat('9999999', '99,99,999');

// ---------------------------------------------------------------------------
section('formatting: crore range');
// ---------------------------------------------------------------------------
testFormat('10000000', '1,00,00,000');
testFormat('99999999', '9,99,99,999');
testFormat('100000000', '10,00,00,000');
testFormat('250000000', '25,00,00,000');
testFormat('999999999', '99,99,99,999');

// ---------------------------------------------------------------------------
section('formatting: beyond crore (matches reference table)');
// ---------------------------------------------------------------------------
testFormat('1000000000', '1,00,00,00,000');
testFormat('10000000000', '10,00,00,00,000');
testFormat('100000000000', '1,00,00,00,00,000');
testFormat('1000000000000', '10,00,00,00,00,000');
testFormat('10000000000000', '1,00,00,00,00,00,000');
testFormat('100000000000000', '10,00,00,00,00,00,000');

// ---------------------------------------------------------------------------
section('formatting: negative numbers');
// ---------------------------------------------------------------------------
testFormat('-1', '-1');
testFormat('-1234', '-1,234');
testFormat('-123456', '-1,23,456');
testFormat('-1234567', '-12,34,567');
testFormat('-12345678', '-1,23,45,678');

// ---------------------------------------------------------------------------
section('formatting: decimals (fractional part untouched)');
// ---------------------------------------------------------------------------
testFormat('25.75', '25.75');
testFormat('1234.5', '1,234.5');
testFormat('123456.789', '1,23,456.789');
testFormat('0.5', '0.5');
testFormat('-1234.56', '-1,234.56');
testFormat('1234567.000001', '12,34,567.000001');

// ---------------------------------------------------------------------------
section('formatting: very large numbers (no precision limit)');
// ---------------------------------------------------------------------------
testFormat('100000000000000000000', '10,00,00,00,00,00,00,00,00,000');
testFormat('999999999999999999999999', '9,99,99,99,99,99,99,99,99,99,99,999');

if (require.main === module) {
  const { failCount } = printSummary('INDIAN FORMATTING');
  process.exitCode = failCount > 0 ? 1 : 0;
}
