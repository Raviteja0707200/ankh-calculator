/**
 * 01-arithmetic.test.js
 * Basic arithmetic, operator precedence, associativity, and parentheses.
 */

'use strict';

const { test, section, printSummary } = require('./test-harness.js');

// ---------------------------------------------------------------------------
section('basic arithmetic');
// ---------------------------------------------------------------------------
test('25+18', '43');
test('25-10', '15');
test('25*5', '125');
test('100/4', '25');
test('25.75', '25.75');
test('0.00025', '0.00025');
test('-25', '-25');
test('(-25)', '-25');
test('25--5', '30');
test('5*-3', '-15');

// ---------------------------------------------------------------------------
section('exhaustive small-integer addition/subtraction (0-99)');
// ---------------------------------------------------------------------------
for (let a = 0; a <= 99; a += 3) {
  for (let b = 0; b <= 99; b += 7) {
    test(`${a}+${b}`, String(a + b));
    test(`${a}-${b}`, String(a - b));
  }
}

// ---------------------------------------------------------------------------
section('exhaustive small-integer multiplication/division (1-30)');
// ---------------------------------------------------------------------------
for (let a = 1; a <= 30; a++) {
  for (let b = 1; b <= 30; b++) {
    test(`${a}*${b}`, String(a * b));
    if (a % b === 0) test(`${a}/${b}`, String(a / b));
  }
}

// ---------------------------------------------------------------------------
section('operator precedence: * / before + -');
// ---------------------------------------------------------------------------
test('2+3*4', '14');
test('2*3+4', '10');
test('2+3*4-5', '9');
test('20-4/2', '18');
test('2*3-4*5', '-14');
test('10/2+3*4', '17');
test('10+2*3-4/2', '14');
test('1+2+3*4*5-6/3', '61');
test('100-10*5+3', '53');
test('2*2*2+2', '10');
test('2+2*2*2', '10');

// ---------------------------------------------------------------------------
section('power (^) precedence and right-associativity');
// ---------------------------------------------------------------------------
test('2^3', '8');
test('2^3^2', '512'); // right-assoc: 2^(3^2) = 2^9 = 512
test('2+3^2', '11');
test('2*3^2', '18');
test('(2^3)^2', '64');
test('2^(3+1)', '16');
test('3^0', '1');
test('0^3', '0');
test('0^0', '1');
test('5^1', '5');
test('2^-2', '0.25');
test('10^-3', '0.001');
test('(-2)^2', '4');
test('(-2)^3', '-8');

// ---------------------------------------------------------------------------
section('parentheses: nesting and grouping');
// ---------------------------------------------------------------------------
test('(1+2)*3', '9');
test('1+(2*3)', '7');
test('((1+2)*3)', '9');
test('(((1)))', '1');
test('((25+5)*8)^2', '57600');
test('(2+3)*(4+5)', '45');
test('((2+3)*(4+5))', '45');
test('(((((5)))))', '5');
test('2*(3+(4*(5+1)))', '54');
test('((1+1)+(1+1))*((1+1)+(1+1))', '16');

// Deep nesting stress (within MAX_PAREN_DEPTH)
{
  let expr = '';
  const depth = 200;
  for (let i = 0; i < depth; i++) expr += '(';
  expr += '7';
  for (let i = 0; i < depth; i++) expr += ')';
  test(expr, '7');
}
{
  let expr = '(1+1)';
  for (let i = 0; i < 30; i++) expr = `(${expr}+1)`;
  // (1+1)=2, then wrapped 30 times adding 1 each time => 2 + 30 = 32
  test(expr, '32');
}

// ---------------------------------------------------------------------------
section('unary operators chained');
// ---------------------------------------------------------------------------
test('--5', '5');
test('---5', '-5');
test('----5', '5');
test('+5', '5');
test('++5', '5');
test('+-5', '-5');
test('-+5', '-5');
test('5+-5', '0');
test('5-+5', '0');
test('5--5', '10');
test('5++5', '10');
test('-5+-5', '-10');
test('-(5+5)', '-10');
test('-(-(5))', '5');
test('-(-(-5))', '-5');

// ---------------------------------------------------------------------------
section('decimals: arithmetic without floating point error');
// ---------------------------------------------------------------------------
test('0.1+0.2', '0.3');
test('0.1+0.2+0.3', '0.6');
test('1.1+2.2', '3.3');
test('0.1*3', '0.3');
test('1-0.9', '0.1');
test('0.7+0.1', '0.8');
test('4.35*100', '435');
test('1.005*100', '100.5');
test('0.1+0.1+0.1', '0.3');
test('2.675*100', '267.5');
test('10.5/2', '5.25');
test('3.14159+2.71828', '5.85987');
test('100.5-0.5', '100');
test('0.0001+0.0002', '0.0003');
test('123.456+876.544', '1000');

// ---------------------------------------------------------------------------
section('large numbers / many digits');
// ---------------------------------------------------------------------------
test('999999999999999999+1', '1000000000000000000');
test('123456789123456789+987654321987654321', '1111111111111111110');
test('99999999999999999999*99999999999999999999', (99999999999999999999n * 99999999999999999999n).toString());

if (require.main === module) {
  const { failCount } = printSummary('ARITHMETIC & PRECEDENCE');
  process.exitCode = failCount > 0 ? 1 : 0;
}
